"""Render existing evidence for people without inventing reviews or prose."""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import yaml

MARKER = "<!-- Generated by report_views.py; edit the source records, not this view. -->"


def load(experiment: Path, relative: str) -> dict:
    return yaml.safe_load((experiment / relative).read_text(encoding="utf-8")) or {}


def render(experiment: Path, view: str) -> str:
    lines = [MARKER, ""]
    if view == "writing":
        lines += ["# 執筆案内", "", "本文と考察は本人が書きます。以下は説明する対象と証拠の案内であり、回答例ではありません。", ""]
        for t in load(experiment, "spec/ASSIGNMENT_REQUIREMENTS.yaml").get("task_scopes", []):
            lines += [f"## {t['task_id']}: {t['title']}", "", f"実習書の範囲: {t['instruction_scope']}",
                      "使用する知識・手法: " + " / ".join(t["allowed_knowledge"]),
                      "持ち込まない内容: " + (" / ".join(t["excluded_knowledge"]) or "追加制限なし。後続課題の解法・結果は持ち込まない。"),
                      "指定条件: " + ", ".join(t["requirement_ids"]), f"コメント方針: {t['comment_policy']}", ""]
        for s in load(experiment, "spec/WRITING_PLAN.yaml")["slots"]:
            lines += [f"## {s['display_label']} — {s['section']}", "", f"説明すること: {s['purpose']}",
                      "対象課題: " + (", ".join(s.get("task_ids", [])) or "旧形式・未設定"),
                      "扱う論点: " + " / ".join(s["required_points"]),
                      "使える証拠: " + (", ".join(s["evidence_ids"]) or "実習書・本人の実施記録"),
                      "参照する図表・式: " + (", ".join(s["planned_references"]) or "なし"),
                      "本人が考えること: " + s.get("student_judgment", "上の論点について、事実と自分の解釈を区別して説明する。新たな主張には根拠が必要。"), ""]
        lines += ["数値・算出方法: RESULT_TRACEABILITY.md / 出典本文と確認箇所: SOURCE_AUDIT.md", ""]
    elif view == "sources":
        lines += ["# 出典検証記録", "", "以下は保存済み記録の表示です。生成処理はWeb本文を検証せず、確認状態を変更しません。", ""]
        for s in load(experiment, "spec/SOURCES.yaml")["sources"]:
            v = s["verification"]
            lines += [f"## {s['source_id']}: {s['title']}", "", f"URL: {s['url']}",
                      f"発行主体: {s['organization']} / 言語: {s['language']} / 種別: {s['source_class']}",
                      f"確認日: {s['accessed_at']} / 状態: {v['status']}", f"確認箇所: {v['locator']}",
                      f"内容一致: {v['match_note']}", f"選定理由: {v['selection_note']}", ""]
        for c in load(experiment, "spec/CLAIMS.yaml")["claims"]:
            if c.get("source_ids"):
                lines += [f"### {c['claim_id']}: {c['text']}", "", f"本文位置: {c['report_locator']}",
                          "出典: " + ", ".join(c["source_ids"]), f"採否: {c['status']} / {c['verification_note']}", ""]
    elif view == "evaluation":
        p = load(experiment, "quality/PROFESSOR_REVIEW.yaml")
        lines += ["# 教授視点の模擬評価", "", f"確認日: {p['reviewed_at']}", ""]
        for r in p["rubric"]:
            lines += [f"## {r['rubric_id']}: {r['verdict']}", "", "本文位置: " + " / ".join(r["report_locators"]),
                      "根拠: " + " / ".join(r["evidence"]), f"指摘: {r['criticism']}", f"改善案: {r['improvement']}",
                      "点数: " + (str(r["score"]) if r["score"] is not None else "採点しない（尺度・配点なし）"), ""]
        o = p["overall"]
        for r in p.get("task_scope_reviews", []):
            lines += [f"## 学習範囲 {r['task_id']}: {r['status']}", "", r["evidence"], ""]
        lines += [f"総合判断: {o['verdict']}", "総合点: " + (str(o["score_percent"]) if o["score_percent"] is not None else "なし"),
                  "強み: " + " / ".join(o["strengths"]), "弱点: " + " / ".join(o["weaknesses"]), "", p["limitations"], ""]
    else:
        raise ValueError(f"unknown view: {view}")
    return "\n".join(lines)


TARGETS = {"writing": "workflow/WRITING_BRIEF.md", "sources": "SOURCE_AUDIT.md", "evaluation": "PROFESSOR_EVALUATION.md"}


def generate(experiment: Path, view: str, replace_legacy: bool = False) -> Path:
    text = render(experiment, view)
    target = experiment / TARGETS[view]
    if target.is_file():
        old = target.read_bytes()
        if target.read_text(encoding="utf-8") == text:
            return target
        if not target.read_text(encoding="utf-8").startswith(MARKER):
            if not replace_legacy:
                raise ValueError(f"handwritten file preserved: {target}; use --replace-legacy after checking unique notes")
            backup = experiment / "quality/view-backups" / hashlib.sha256(old).hexdigest() / target.name
            backup.parent.mkdir(parents=True, exist_ok=True)
            backup.write_bytes(old)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8", newline="\n")
    return target


def sync_rubric(experiment: Path) -> None:
    """Project the final rubric judgement; preserve independent technical checks."""
    p = load(experiment, "quality/PROFESSOR_REVIEW.yaml")
    q = load(experiment, "quality/QUALITY_REVIEW.yaml")
    rows = rubric_projection(p)
    if rows != q["rubric"] or q.get("rubric_source") != "professor_review":
        q.update(rubric=rows, rubric_source="professor_review", reviewed_pdf_sha256=None, reviewed_inputs_digest=None)
        (experiment / "quality/QUALITY_REVIEW.yaml").write_text(yaml.safe_dump(q, allow_unicode=True, sort_keys=False), encoding="utf-8", newline="\n")


def rubric_projection(professor: dict) -> list[dict]:
    mapping = {"met": "passed", "partially_met": "failed", "not_met": "failed",
               "undetermined": "failed", "not_applicable": "not_applicable"}
    return [{"rubric_id": r["rubric_id"], "status": mapping[r["verdict"]],
             "report_locators": r["report_locators"], "evidence": r["evidence"],
             "note": r["criticism"]} for r in professor["rubric"]]


def freshness_errors(experiment: Path, view: str) -> list[str]:
    target = experiment / TARGETS[view]
    if not target.is_file() or not target.read_text(encoding="utf-8").startswith(MARKER):
        return []  # Existing manually audited documents remain supported.
    try:
        current = render(experiment, view)
    except (KeyError, TypeError, ValueError) as exc:
        return [f"cannot render {view}: {exc}"]
    return [] if target.read_text(encoding="utf-8") == current else [f"generated {view} view is stale; rerun report_views.py"]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("experiment", type=Path)
    parser.add_argument("view", choices=TARGETS)
    parser.add_argument("--replace-legacy", action="store_true")
    parser.add_argument("--sync-rubric", action="store_true")
    args = parser.parse_args()
    if args.sync_rubric:
        if args.view != "evaluation":
            parser.error("--sync-rubric requires evaluation")
        # Refuse a handwritten output before touching the structured review.
        generate(args.experiment, args.view, args.replace_legacy)
        sync_rubric(args.experiment)
    else:
        generate(args.experiment, args.view, args.replace_legacy)
    print(args.experiment / TARGETS[args.view])


if __name__ == "__main__":
    main()
